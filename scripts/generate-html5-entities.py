#!/usr/bin/env python3
"""Generate the CommonMark-compatible HTML5 entity table.

Source URL: https://raw.githubusercontent.com/w3c/html/2ef7a579bcfd2693b98df35f20e51dff60e3fbef/entities.json
Retrieval method: HTTP GET the pinned raw URL and save its response bytes
unchanged as data/whatwg-entities.json. The SHA-256 below verifies the snapshot.
"""

import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path


SOURCE_URL = (
    "https://raw.githubusercontent.com/w3c/html/"
    "2ef7a579bcfd2693b98df35f20e51dff60e3fbef/entities.json"
)
SOURCE_IDENTIFIER = "w3c/html commit 2ef7a579bcfd2693b98df35f20e51dff60e3fbef"
SOURCE_SHA256 = "3d029331b82668ac319bc81802de45b24396df76816d9ba6cf8807c0a1e59a29"
ATTRIBUTION = "Copyright © WHATWG."
LICENSE = "CC BY 4.0; portions incorporated into source code are BSD 3-Clause."

ROOT = Path(__file__).resolve().parent.parent
SOURCE_PATH = ROOT / "data" / "whatwg-entities.json"
OUTPUT_PATH = ROOT / "src" / "html-entities-data.lisp"


def source_entries():
    raw = SOURCE_PATH.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(
            f"{SOURCE_PATH.relative_to(ROOT)} SHA-256 mismatch: "
            f"expected {SOURCE_SHA256}, got {digest}"
        )

    source = json.loads(raw)
    if not isinstance(source, dict):
        raise ValueError("the entity source must be a JSON object")

    entries = []
    for source_name, record in source.items():
        if not isinstance(source_name, str) or not source_name.startswith("&"):
            raise ValueError(f"invalid entity name: {source_name!r}")
        if not source_name.endswith(";"):
            continue

        if not isinstance(record, dict):
            raise ValueError(f"invalid entity record: {source_name!r}")
        codepoints = record.get("codepoints")
        if not isinstance(codepoints, list) or not codepoints:
            raise ValueError(f"missing code points: {source_name!r}")
        if any(
            isinstance(codepoint, bool)
            or not isinstance(codepoint, int)
            or not 0 <= codepoint <= 0x10FFFF
            or 0xD800 <= codepoint <= 0xDFFF
            for codepoint in codepoints
        ):
            raise ValueError(f"invalid code point: {source_name!r}")

        characters = record.get("characters")
        if characters != "".join(chr(codepoint) for codepoint in codepoints):
            raise ValueError(f"character sequence mismatch: {source_name!r}")

        entries.append((source_name[1:], codepoints))

    entries.sort(key=lambda entry: entry[0])
    return entries


def render_lisp(entries):
    lines = [
        ";;; Generated by scripts/generate-html5-entities.py. Do not edit by hand.",
        ";;; Source: w3c/html repository entities.json snapshot.",
        f";;; Source URL: {SOURCE_URL}",
        f";;; Source identifier: {SOURCE_IDENTIFIER}",
        f";;; Source SHA-256: {SOURCE_SHA256}",
        f";;; Attribution: {ATTRIBUTION}",
        f";;; License: {LICENSE}",
        ";;; Only semicolon-terminated names are stored, as required by CommonMark.",
        "",
        "(in-package #:cl-markdown-kit)",
        "",
        "(defparameter *html5-entities*",
        f"  (let ((table (make-hash-table :test 'equal :size {len(entries)})))",
        "    (dolist (entry",
        "             '(",
    ]

    for name, codepoints in entries:
        lisp_codepoints = " ".join(f"#x{codepoint:04X}" for codepoint in codepoints)
        lines.append(f'               ("{name}" {lisp_codepoints})')

    lines.extend(
        [
            "               ))",
            "      (setf (gethash (car entry) table)",
            "            (map 'string #'code-char (cdr entry))))",
            "    table))",
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated Lisp file is out of date",
    )
    args = parser.parse_args()

    try:
        expected = render_lisp(source_entries())
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    if args.check:
        try:
            actual = OUTPUT_PATH.read_bytes()
        except OSError as error:
            print(f"error: {error}", file=sys.stderr)
            return 1
        if actual != expected:
            before = actual.decode("utf-8", errors="replace").splitlines()
            after = expected.decode("utf-8").splitlines()
            diff = difflib.unified_diff(
                before,
                after,
                fromfile=str(OUTPUT_PATH.relative_to(ROOT)),
                tofile="expected generated output",
                lineterm="",
            )
            print("\n".join(diff), file=sys.stderr)
            return 1
        print(f"verified {OUTPUT_PATH.relative_to(ROOT)} ({len(expected)} bytes)")
        return 0

    OUTPUT_PATH.write_bytes(expected)
    print(f"wrote {OUTPUT_PATH.relative_to(ROOT)} ({len(expected)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
